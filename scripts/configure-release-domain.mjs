#!/usr/bin/env node

import { isIP } from "node:net";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const MANIFEST = path.join(ROOT, "release-target.json");
const MINI_TARGET = path.join(ROOT, "mini-program", "release-target.js");
const IOS_TARGET = path.join(ROOT, "ios", "ZhishiMobile", "ReleaseTarget.swift");
const ARTIFACT_DIR = path.join(ROOT, ".artifacts", "release");
const PLACEHOLDER_ORIGIN = "https://zhishiyan.invalid";

export function normalizeRootDomain(input) {
  const raw = String(input || "").trim().toLowerCase();
  if (!raw) throw new Error("请填写已经购买或准备购买的根域名，例如 zhishiyan.cn");
  if (raw.includes("://") || /[/?#@:\\]/.test(raw)) throw new Error("只填写根域名，不要包含 https://、路径、端口或账号信息");
  let url;
  try { url = new URL(`https://${raw}`); } catch { throw new Error("域名格式无法识别"); }
  const hostname = url.hostname.toLowerCase();
  if (!hostname.includes(".") || isIP(hostname) || hostname === "localhost" || hostname.endsWith(".local") || hostname.endsWith(".invalid")) throw new Error("必须使用可注册的公网域名，不能使用 IP、localhost 或占位域名");
  if (hostname.startsWith("www.") || hostname.startsWith("api.")) throw new Error("请填写根域名，不要填写 www 或 api 子域名");
  for (const label of hostname.split(".")) if (!label || label.startsWith("-") || label.endsWith("-")) throw new Error("域名标签不能留空或以连字符开头、结尾");
  return hostname;
}

export function releaseTarget(rootDomain = "") {
  if (!rootDomain) return { rootDomain: "", webOrigin: PLACEHOLDER_ORIGIN, apiOrigin: PLACEHOLDER_ORIGIN };
  const normalized = normalizeRootDomain(rootDomain);
  return {
    rootDomain: normalized,
    webOrigin: `https://${normalized}`,
    apiOrigin: `https://api.${normalized}`,
  };
}

function miniSource(target) {
  return `// Generated by \`npm run release:domain -- your-domain.cn\`.\nmodule.exports = Object.freeze({\n  configured: ${Boolean(target.rootDomain)},\n  rootDomain: ${JSON.stringify(target.rootDomain)},\n  webOrigin: ${JSON.stringify(target.webOrigin)},\n  apiOrigin: ${JSON.stringify(target.apiOrigin)},\n});\n`;
}

function swiftSource(target) {
  return `import Foundation\n\n// Generated by \`npm run release:domain -- your-domain.cn\`.\nenum ReleaseTarget {\n    static let configured = ${target.rootDomain ? "true" : "false"}\n    static let rootDomain = ${JSON.stringify(target.rootDomain)}\n    static let webOrigin = ${JSON.stringify(target.webOrigin)}\n    static let apiOrigin = ${JSON.stringify(target.apiOrigin)}\n\n    static var apiBaseURL: URL? {\n        configured ? URL(string: apiOrigin) : nil\n    }\n}\n`;
}

export function generatedSources(target) {
  return {
    manifest: `${JSON.stringify(target, null, 2)}\n`,
    mini: miniSource(target),
    ios: swiftSource(target),
  };
}

async function checkSynchronized() {
  const manifest = JSON.parse(await readFile(MANIFEST, "utf8"));
  const expected = generatedSources(releaseTarget(manifest.rootDomain || ""));
  const actual = {
    manifest: await readFile(MANIFEST, "utf8"),
    mini: await readFile(MINI_TARGET, "utf8"),
    ios: await readFile(IOS_TARGET, "utf8"),
  };
  const mismatches = Object.keys(expected).filter((key) => expected[key] !== actual[key]);
  if (mismatches.length) throw new Error(`三端域名配置不同步：${mismatches.join("、")}；请重新运行 release:domain`);
  console.log(manifest.rootDomain ? `✓ 网站使用 ${manifest.webOrigin}；客户端 API 使用 ${manifest.apiOrigin}` : "✓ 三端仍使用不可访问占位域名，尚未误连生产环境");
}

async function configure(input) {
  const target = releaseTarget(input);
  const generated = generatedSources(target);
  await Promise.all([
    writeFile(MANIFEST, generated.manifest),
    writeFile(MINI_TARGET, generated.mini),
    writeFile(IOS_TARGET, generated.ios),
  ]);
  await mkdir(ARTIFACT_DIR, { recursive: true });
  const report = [
    "# 正式域名接入结果",
    "",
    `- 根域名：\`${target.rootDomain}\``,
    `- 网站、PWA、iOS 地址：\`${target.webOrigin}\``,
    `- 小程序 request/uploadFile/downloadFile 合法域名：\`${target.apiOrigin}\``,
    "- DNS：根域名 `@` 指向正式服务器；可选 `www` 只做跳转，不作为第二套应用地址。",
    "- 状态：只写入公开地址配置；没有部署、修改 DNS、上传微信版本或提交 App Store。",
    "",
  ].join("\n");
  await writeFile(path.join(ARTIFACT_DIR, "domain-config.md"), report);
  console.log(`✓ 网站使用 ${target.webOrigin}；小程序和 iOS API 使用 ${target.apiOrigin}`);
  console.log("下一步：完成 DNS、HTTPS 和 ICP 后运行 npm run mobile:check -- --strict-external");
}

async function main() {
  if (process.argv.includes("--check")) return checkSynchronized();
  const positional = process.argv.slice(2).find((value) => !value.startsWith("--"));
  await configure(positional || process.env.ZHISHI_ROOT_DOMAIN);
}

if (path.resolve(process.argv[1] || "") === fileURLToPath(import.meta.url)) main().catch((error) => {
  console.error(`域名配置失败：${error instanceof Error ? error.message : error}`);
  process.exitCode = 1;
});
